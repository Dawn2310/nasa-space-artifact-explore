import assert from 'node:assert/strict';
import { BADGES, REWARD_KEY, createRewardBook } from '../src/features/rewards/rewards.ts';
import { readFileSync } from 'node:fs';
const catalog = JSON.parse(readFileSync(new URL('../content/catalog.json', import.meta.url)));
assert.deepEqual(Object.keys(BADGES).sort(), catalog.artifacts.map(a => a.id).sort(), 'Every artifact has exactly one reward');
const saved = new Map();
const storage = { getItem: key => saved.get(key) ?? null, setItem: (key, value) => saved.set(key, value) };
const book = createRewardBook(storage);
assert.equal(book.read().length, 0, 'Merely opening the app does not award a badge');
assert.equal(book.claim('sojourner').added, true);
assert.equal(book.claim('sojourner').added, false, 'Replays cannot duplicate rewards');
assert.equal(createRewardBook(storage).read()[0].id, 'sojourner', 'A new visit restores the saved badge');
assert.equal(book.read().some(b => b.id === 'spirit'), false, 'Skipping to another stop does not award that stop');
createRewardBook(storage).claim('dawn');
book.claim('spirit');
assert.equal(createRewardBook(storage).read().length, 3, 'Changes made from another same-origin mission document are preserved');
assert.equal(book.claim('not-a-mission').added, false);
saved.set(REWARD_KEY, '{bad json');
assert.doesNotThrow(() => createRewardBook(storage).read());
saved.set(REWARD_KEY, JSON.stringify([{ id: 'fake', earnedAt: new Date().toISOString() }, { id: 'dawn', earnedAt: 'not a date' }]));
assert.equal(createRewardBook(storage).read().length, 0);
const blocked = createRewardBook({ getItem() { throw Error('blocked'); }, setItem() { throw Error('quota'); } });
assert.equal(blocked.claim('kepler').persisted, false);
assert.equal(blocked.read().length, 1, 'Blocked storage still supports the current visit');
console.log('rewards.check: all 17 badges, completion-only claims, replay dedupe, persistence, cross-document updates and storage failures passed');
